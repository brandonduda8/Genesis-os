"""Asset vault: provenance-first promotion, honest rights, replayable audit, signed manifests."""
import base64
import json
import os
import sqlite3
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
from vault import COMMERCIAL_OK, Vault, VaultError, ed25519_signer, verify_manifest  # noqa: E402

STOCK = {"origin": "stock", "licence": "CC0-1.0", "pack": "p", "media_type": "model/gltf-binary",
         "provenance": {"source": "npm:@netforge/asset-library-files@0.2.0/library/x.glb"}}


def mkfile(d, name, data):
    p = os.path.join(d, name)
    with open(p, "wb") as f:
        f.write(data)
    return p


class VaultTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.v = Vault.init(os.path.join(self.tmp, "vault"))
        self.a = self.v.add(mkfile(self.tmp, "a.glb", b"model-a"), name="style.lowpoly.ghost", actor="t", **STOCK)["sha256"]

    def test_content_addressed_and_read_only(self):
        p = self.v.object_path(self.a)
        self.assertTrue(p.endswith(self.a))
        self.assertEqual(os.stat(p).st_mode & 0o222, 0)
        again = self.v.add(mkfile(self.tmp, "a2.glb", b"model-a"), name="dup", actor="t", **STOCK)
        self.assertEqual(again["status"], "already-promoted")

    def test_everything_enters_not_rights_clean(self):
        row = self.v.db.execute("SELECT rights_clean FROM assets WHERE sha256=?", (self.a,)).fetchone()
        self.assertEqual(row[0], 0)

    def test_provenance_and_licence_required_and_streams_refused(self):
        f = mkfile(self.tmp, "b.ogg", b"sound")
        for bad in ({**STOCK, "provenance": {}}, {**STOCK, "licence": ""}, {**STOCK, "origin": "stream"},
                    {**STOCK, "origin": "genesis"}):  # genesis without a generator
            with self.assertRaises(VaultError):
                self.v.add(f, name="b", actor="t", **bad)

    def test_staged_file_tampered_before_promotion_is_refused(self):
        sha = self.v.stage(mkfile(self.tmp, "c.png", b"orig"))
        with open(os.path.join(self.v.root, "staging", sha), "wb") as f:
            f.write(b"swapped")
        with self.assertRaises(VaultError):
            self.v.promote(sha, name="c", actor="t", **{k: STOCK[k] for k in STOCK if k != "media_type"},
                           media_type="image/png")

    def test_rights_need_evidence_and_a_commercial_licence(self):
        with self.assertRaises(VaultError):
            self.v.set_rights(self.a, True, evidence="", actor="zane")
        self.v.set_rights(self.a, True, evidence="read asset-library-files/NOTICE: Quaternius CC0 1.0", actor="zane")
        nc = self.v.add(mkfile(self.tmp, "nc.png", b"nc"), name="nc", actor="t",
                        **{**STOCK, "licence": "CC-BY-NC-4.0"})["sha256"]
        with self.assertRaises(VaultError):
            self.v.set_rights(nc, True, evidence="it's fine", actor="zane")
        self.assertNotIn("CC-BY-NC-4.0", COMMERCIAL_OK)

    def test_cc0_stock_is_rights_clean_but_never_original(self):
        self.v.bind_slot("emberwatch", "style.lowpoly.ghost", self.a, actor="t")
        self.v.set_rights(self.a, True, evidence="NOTICE read", actor="zane")
        r = self.v.title_report("emberwatch")
        self.assertEqual((r["rights_clean"], r["genesis_original"], r["original"]), (1, 0, False))
        g = self.v.add(mkfile(self.tmp, "g.glb", b"genesis-ghost"), name="ghost-v1", actor="t",
                       **{**STOCK, "origin": "genesis", "licence": "OWNED-BRANDON",
                          "provenance": {"source": "asset-service", "generator": "lane:media-gen job:42"}})["sha256"]
        self.v.set_rights(g, True, evidence="generated by the fleet for Brandon", actor="zane")
        self.v.bind_slot("emberwatch", "style.lowpoly.ghost", g, actor="t")
        r = self.v.title_report("emberwatch")
        self.assertTrue(r["original"])
        self.assertEqual(r["remaining_for_original"], [])

    def test_slots_accept_only_vault_assets(self):
        with self.assertRaises(VaultError):
            self.v.bind_slot("emberwatch", "x", "f" * 64, actor="t")

    def test_audit_replay_clean_then_catches_each_kind_of_damage(self):
        self.assertEqual(self.v.audit_replay()["problems"], [])
        p = self.v.object_path(self.a)
        os.chmod(p, 0o644)
        with open(p, "wb") as f:
            f.write(b"tampered")
        self.assertIn("do not match", " ".join(self.v.audit_replay()["problems"]))
        os.remove(p)
        self.assertIn("missing on disk", " ".join(self.v.audit_replay()["problems"]))

    def test_audit_log_edits_and_deletions_are_detected(self):
        self.v.set_rights(self.a, True, evidence="NOTICE read", actor="zane")
        lines = open(self.v.audit_path).read().splitlines()
        e = json.loads(lines[1])
        e["data"]["licence"] = "OWNED-BRANDON"  # rewrite history
        open(self.v.audit_path, "w").write("\n".join([lines[0], json.dumps(e)] + lines[2:]) + "\n")
        self.assertTrue(any("edited" in p for p in self.v.verify_audit_chain()))
        open(self.v.audit_path, "w").write("\n".join([lines[0]] + lines[2:]) + "\n")  # delete the promote line
        probs = self.v.audit_replay()["problems"]
        self.assertTrue(any("chain broken" in p for p in probs))
        self.assertTrue(any("no promote entry" in p for p in probs))

    def test_catalog_row_without_file_and_file_without_row(self):
        con = sqlite3.connect(os.path.join(self.v.root, "CATALOG.sqlite"))
        con.execute("DELETE FROM assets")
        con.commit()
        self.assertIn("no catalog row", " ".join(Vault(self.v.root).audit_replay()["problems"]))

    def test_signed_manifest_verifies_and_detects_tampering(self):
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
        from cryptography.hazmat.primitives import serialization
        key = os.path.join(self.tmp, "k")
        raw = Ed25519PrivateKey.generate().private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                                                          serialization.NoEncryption())
        fd = os.open(key, os.O_WRONLY | os.O_CREAT, 0o600)
        os.write(fd, base64.b64encode(raw))
        os.close(fd)
        signer, pub = ed25519_signer(key)
        doc = self.v.pack_manifest("p", signer=signer, signer_pub=pub)
        self.assertEqual(verify_manifest(doc, self.v, trusted_pub=pub), [])
        doc["manifest"]["entries"][0]["licence"] = "OWNED-BRANDON"
        self.assertTrue(verify_manifest(doc, self.v, trusted_pub=pub))
        unsigned = self.v.pack_manifest("p")
        self.assertIn("unsigned manifest", verify_manifest(unsigned, trusted_pub=pub))


if __name__ == "__main__":
    unittest.main()

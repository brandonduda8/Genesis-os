def render_pay_page(invoice, config=None):
    """Render ONE simple pay page for an invoice: amount due, then the
    four rails — a payer taps one button or follows one short instruction
    list. No card fields, no API keys, no accounts to create here."""
    config = config or load_config()
    rails = build_rails(invoice, config)
    number = html.escape(str(invoice.get("invoice_number") or ""))
    business = html.escape(config.get("business_name", ""))
    cents = int(invoice.get("total_cents", invoice.get("amount_cents", 0)))
    out = ["<!DOCTYPE html><html><head><meta charset='utf-8'>",
           "<meta name='viewport' content='width=device-width,initial-scale=1'>",
           "<title>Pay %s — %s</title><style>%s</style></head><body>"
           % (number, business, _PAGE_CSS),
           "<div class='card'>",
           "<h1>%s</h1>" % business,
           "<div class='muted'>Invoice <code>%s</code></div>" % number,
           "<div class='due'>%s</div>" % fmt_money(cents),
           "<div class='muted'>Pick whichever app you already use — "
           "every option pays the exact amount above. No card needed "
           "here.</div>"]
    for r in rails:
        out.append("<div class='rail'><h2>%s</h2>" % html.escape(r["label"]))
        if r["kind"] == "link":
            out.append("<a class='btn' href='%s'>%s</a>"
                       % (html.escape(r["url"], quote=True),
                          html.escape(r["button"])))
            out.append("<div class='note'>%s</div>"
                       % html.escape(r["instruction"]))
            if r.get("qr_svg"):
                out.append("<div class='qr'>%s</div>" % r["qr_svg"])
        else:
            out.append("<ol>%s</ol>" % "".join(
                "<li>%s</li>" % html.escape(s) for s in r["steps"]))
            out.append("<div class='note'>Amount: <b>%s</b> · Note: "
                       "<code>%s</code></div>"
                       % (html.escape(r["amount"]), html.escape(r["note"])))
        out.append("</div>")
    out.append("<div class='muted' style='margin-top:12px'>After you pay, "
               "we confirm receipt against the invoice number in your "
               "note — keep it exactly as shown.</div>")
    out.append("</div></body></html>")
    return "\n".join(out)

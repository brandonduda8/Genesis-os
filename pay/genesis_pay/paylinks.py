def fmt_money(cents, currency="USD"):
    cents = int(cents)
    sign = "-" if cents < 0 else ""
    cents = abs(cents)
    return "%s$%d.%02d" % (sign, cents // 100, cents % 100)


def _paypal_amount(cents):
    """PayPal.Me amount segment: '297' for whole dollars, else '75.50'."""
    cents = int(cents)
    if cents % 100 == 0:
        return str(cents // 100)
    return "%d.%02d" % (cents // 100, cents % 100)


def load_config(path=None):
    """Load rails_config.json (merged over nothing — the file IS the
    config of record; a missing file is a loud error, not a guess)."""
    path = path or CONFIG_PATH
    with open(path, encoding="utf-8") as f:
        return json.load(f)



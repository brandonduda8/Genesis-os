def build_rails(invoice, config):
    """Build the four payer rails for an Apex-shaped invoice dict.

    Returns a list of rail dicts: kind 'link' (one-tap button + QR) or
    'instruction' (numbered steps); every rail carries the exact amount
    and the note the payer must use (the invoice number).
    """
    number = str(invoice.get("invoice_number") or invoice.get("id") or "")
    cents = int(invoice.get("total_cents", invoice.get("amount_cents", 0)))
    amount = fmt_money(cents, invoice.get("currency", "USD"))
    note = number
    rails = []

    ca = config.get("cash_app", {})
    if ca.get("cashtag"):
        url = "https://cash.app/$%s" % ca["cashtag"]
        rails.append({
            "rail": "cash_app", "label": "Cash App", "kind": "link",
            "url": url, "qr_svg": qr_svg(url), "amount": amount,
            "amount_cents": cents, "note": note,
            "button": "Open Cash App — pay %s" % amount,
            "instruction": "Tap the button (or scan the QR), enter exactly "
                           "%s, and put %s in the note." % (amount, note),
            "status": "VERIFIED",
            "status_detail": ca.get("link_status", ""),
        })

    pp = config.get("paypal", {})
    handle = pp.get("paypal_me_handle")
    if handle:
        url = "https://www.paypal.me/%s/%s" % (handle, _paypal_amount(cents))
        rails.append({
            "rail": "paypal", "label": "PayPal", "kind": "link",
            "url": url, "qr_svg": qr_svg(url), "amount": amount,
            "amount_cents": cents, "note": note,
            "button": "Open PayPal — pay %s" % amount,
            "instruction": "The amount is pre-filled. Add %s in the note "
                           "if PayPal asks." % note,
            "status": "VERIFIED",
            "status_detail": pp.get("link_format", ""),
        })
    else:
        rails.append({
            "rail": "paypal", "label": "PayPal", "kind": "instruction",
            "url": None, "qr_svg": None, "amount": amount,
            "amount_cents": cents, "note": note,
            "steps": ["Open PayPal and tap Send.",
                      "Send to %s." % pp.get("email", ""),
                      "Enter exactly %s." % amount,
                      "Put %s in the note." % note],
            "status": "HANDLE_NEEDED",
            "status_detail": pp.get("link_format", ""),
            "config_needed": pp.get("brandon_step", ""),
        })

    for key in ("current", "onepay"):
        cfg = config.get(key, {})
        app = RAIL_LABELS[key]
        rails.append({
            "rail": key, "label": app, "kind": "instruction",
            "url": None, "qr_svg": None, "amount": amount,
            "amount_cents": cents, "note": note,
            "steps": ["Open the %s app and choose Send money." % app,
                      "Find %s (%s)." % (cfg.get("payee_name", ""),
                                          cfg.get("phone", "")),
                      "Enter exactly %s." % amount,
                      "Put %s in the note/memo." % note],
            "status": "INSTRUCTION",
            "status_detail": cfg.get("link_status", ""),
        })
    return rails


